"""Repository-wide external dependency discovery (M5.2 / M5.6).

``discover_dependencies(root)`` is deterministic, offline and read-only:

1. enumerate files safely (:mod:`patchfrog.dependencies.files` -- secret
   stores are never opened);
2. parse manifests/lockfiles and local OpenAPI specs;
3. scan Python (``ast``) and JS/TS (lexical) sources once each;
4. let every adapter turn observations into evidence and evidence into
   dependencies;
5. attach enclosing symbols to usage sites -- Python through the same
   tree-sitter parser the repository index uses (so qualified names line
   up with Change/Contract Intelligence), JS/TS through a lexical span
   scan.
"""

